async function main() {
  await mongoose.connect(env.MONGODB_URI, { maxPoolSize: 10 });

  const user = await UserModel.findOne().lean();
  if (!user) {
    console.log("User가 없습니다. 먼저 seed.ts를 실행하세요.");
    return;
  }

  const existing = await PromptModel.countDocuments({ title: PROMPTS[0].title });
  if (existing > 0) {
    console.log("2차 프롬프트가 이미 존재합니다. 스킵.");
    return;
  }

  await PromptModel.insertMany(
    PROMPTS.map((p) => ({
      ...p,
      createdBy: user._id,
      likeCount: 0,
      likedBy: [],
    }))
  );
  console.log("2차 프롬프트 6개 등록 완료.");
}

main()
